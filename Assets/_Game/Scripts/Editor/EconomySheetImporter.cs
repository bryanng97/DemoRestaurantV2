using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using DemoRestaurant.Game.Content;
using DemoRestaurant.Logic.Content;
using UnityEditor;
using UnityEngine;

namespace DemoRestaurant.Editor
{
    /// <summary>
    /// DemoRestaurant > Content > Import Economy Sheet: reads the designers' workbook (Docs/Design/*.xlsx), writes
    /// Resources/Content/&lt;pack&gt;/economy.json and a report of ids that don't match the pack's content files
    /// (Docs/Design/economy-import-report.md). Nothing is written when the sheet has errors.
    /// </summary>
    public static class EconomySheetImporter
    {
        private const string Pack = "malaysia";
        private const string DesignFolder = "Docs/Design";
        private const string ReportPath = DesignFolder + "/economy-import-report.md";

        [MenuItem("DemoRestaurant/Content/Import Economy Sheet")]
        public static void ImportLatest()
        {
            string path = LatestSheet();
            if (path == null)
            {
                path = EditorUtility.OpenFilePanel("Economy sheet", DesignFolder, "xlsx");
                if (string.IsNullOrEmpty(path)) return;
            }
            Import(path);
        }

        [MenuItem("DemoRestaurant/Content/Import Economy Sheet From File...")]
        public static void ImportFromFile()
        {
            string path = EditorUtility.OpenFilePanel("Economy sheet", DesignFolder, "xlsx");
            if (!string.IsNullOrEmpty(path)) Import(path);
        }

        public static bool Import(string path)
        {
            Dictionary<string, List<string[]>> sheets;
            try
            {
                sheets = XlsxReader.Read(path);
            }
            catch (Exception e)
            {
                Debug.LogError($"Economy import: can't read {path}: {e.Message}");
                return false;
            }

            var parsed = EconomySheetParser.Parse(sheets, Path.GetFileName(path));
            foreach (var w in parsed.Warnings) Debug.LogWarning("Economy import: " + w);
            if (!parsed.Ok)
            {
                Debug.LogError($"Economy import failed ({parsed.Errors.Count} problems); economy.json was not changed:\n- " +
                               string.Join("\n- ", parsed.Errors));
                return false;
            }

            string jsonPath = $"Assets/_Game/Resources/Content/{Pack}/economy.json";
            File.WriteAllText(jsonPath, JsonUtility.ToJson(parsed.Table, true) + "\n");
            AssetDatabase.ImportAsset(jsonPath);

            string report = BuildReport(parsed.Table);
            File.WriteAllText(ReportPath, report);
            Debug.Log($"Economy import: wrote {jsonPath} from {Path.GetFileName(path)} " +
                      $"({parsed.Table.dishes.Length} dishes, {parsed.Table.ingredients.Length} ingredients, " +
                      $"{parsed.Table.furniture.Length} furniture, {parsed.Table.levels.Length} levels). Report: {ReportPath}");
            return true;
        }

        private static string LatestSheet()
        {
            if (!Directory.Exists(DesignFolder)) return null;
            return Directory.GetFiles(DesignFolder, "*.xlsx")
                .Where(f => !Path.GetFileName(f).StartsWith("~$")) // Excel lock files
                .OrderByDescending(File.GetLastWriteTimeUtc)
                .FirstOrDefault();
        }

        /// <summary>Phase 1 rows compared with the content files, so designers and developers can line up ids.</summary>
        private static string BuildReport(EconomyTable t)
        {
            ContentPack pack = null;
            try { pack = ContentLoader.Load(Pack).Pack; }
            catch (Exception e) { Debug.LogWarning("Economy import: content pack did not load for the report: " + e.Message); }

            var sb = new StringBuilder();
            sb.AppendLine("# Economy import report");
            sb.AppendLine();
            sb.AppendLine($"Generated by DemoRestaurant > Content > Import Economy Sheet from `{t.sourceFile}`.");
            sb.AppendLine("Lists Phase 1 rows (\"In Phase 1\" = Yes) whose ids don't match the game's content files.");
            sb.AppendLine("Ids must match exactly for the sheet's numbers to reach the game.");
            sb.AppendLine();

            if (pack == null)
            {
                sb.AppendLine("Content pack could not be loaded; no comparison.");
                return sb.ToString();
            }

            Section(sb, "Dishes", t.dishes.Where(d => d.inPhase1).Select(d => d.id), pack.Dishes.Select(d => d.Id));
            Section(sb, "Ingredients", t.ingredients.Where(i => i.inPhase1).Select(i => i.id), pack.Ingredients.Select(i => i.Id));
            Section(sb, "Furniture", t.furniture.Where(f => f.inPhase1 && f.category != "floor" && f.category != "wallpaper").Select(f => f.id),
                pack.Furniture.Select(f => f.Id));

            sb.AppendLine("## Recipes (Phase 1 dishes in both)");
            sb.AppendLine();
            bool any = false;
            foreach (var d in t.dishes.Where(d => d.inPhase1))
            {
                var def = pack.Dishes.FirstOrDefault(x => x.Id == d.id);
                if (def == null) continue;
                var game = def.Recipe.Select(r => r.Ingredient.Id).OrderBy(x => x, StringComparer.Ordinal).ToArray();
                var sheet = d.ingredients.OrderBy(x => x, StringComparer.Ordinal).ToArray();
                if (game.SequenceEqual(sheet)) continue;
                sb.AppendLine($"- `{d.id}`: sheet {string.Join(", ", sheet)} · game {string.Join(", ", game)}");
                any = true;
            }
            if (!any) sb.AppendLine("All match.");
            sb.AppendLine();
            return sb.ToString();
        }

        private static void Section(StringBuilder sb, string title, IEnumerable<string> sheetIds, IEnumerable<string> gameIds)
        {
            var sheet = new SortedSet<string>(sheetIds, StringComparer.Ordinal);
            var game = new SortedSet<string>(gameIds, StringComparer.Ordinal);
            sb.AppendLine($"## {title}");
            sb.AppendLine();
            sb.AppendLine($"- Matching: {Join(sheet.Where(game.Contains))}");
            sb.AppendLine($"- In the sheet (Phase 1) but not in the game: {Join(sheet.Where(id => !game.Contains(id)))}");
            sb.AppendLine($"- In the game but not in the sheet's Phase 1: {Join(game.Where(id => !sheet.Contains(id)))}");
            sb.AppendLine();
        }

        private static string Join(IEnumerable<string> ids)
        {
            var list = ids.ToList();
            return list.Count == 0 ? "none" : string.Join(", ", list.Select(i => $"`{i}`"));
        }
    }
}
